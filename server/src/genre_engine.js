// ===== 题材识别 =====
export function normalizeGenre(genre) {
  const g = String(genre || '').trim();
  if (/玄幻|仙侠|修真|奇幻/.test(g)) return '玄幻';
  if (/武侠|江湖|门派/.test(g)) return '武侠';
  if (/都市|现代|职场|商战/.test(g)) return '都市';
  if (/言情|恋爱|甜文|虐恋/.test(g)) return '言情';
  if (/科幻|末世|星际|机甲|赛博/.test(g)) return '科幻';
  if (/历史|穿越.*史|架空.*史/.test(g)) return '历史';
  if (/悬疑|推理|探案|刑侦/.test(g)) return '悬疑';
  if (/游戏|网游|电竞|虚拟/.test(g)) return '游戏';
  return '通用';
}

