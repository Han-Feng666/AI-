/**
 * 生成角色名
 */
export function generateName(genre) {
  const g = normalizeGenre(genre);
  const surname = pickRandom(SURNAMES.split(''));
  let givenPool;
  switch (g) {
    case '玄幻': givenPool = XUANHUAN_NAMES; break;
    case '武侠': givenPool = WUXIA_NAMES; break;
    case '都市': givenPool = DUSHI_NAMES; break;
    case '言情': givenPool = YANQING_NAMES; break;
    case '科幻': givenPool = KEHUAN_NAMES; break;
    case '历史': givenPool = LISHI_NAMES; break;
    case '悬疑': givenPool = XUANYI_NAMES; break;
    case '游戏': givenPool = GAME_NAMES; break;
    default: givenPool = [...DUSHI_NAMES, ...WUXIA_NAMES];
  }
  return surname + pickRandom(givenPool);
}

/**
 * 生成地名
 */
export function generatePlaceName(genre) {
  const g = normalizeGenre(genre);
  const prefix = pickRandom(PLACE_PREFIXES[g] || PLACE_PREFIXES['通用']);
  const suffix = pickRandom(PLACE_SUFFIXES[g] || PLACE_SUFFIXES['通用']);
  return prefix + suffix;
}

/**
 * 生成功法名（玄幻/武侠专用）
 */
export function generateTechniqueName() {
  return pickRandom(TECHNIQUE_PREFIXES) + pickRandom(TECHNIQUE_SUFFIXES);
}

/**
 * 生成势力/组织名
 */
export function generateForceName(genre) {
  const g = normalizeGenre(genre);
  const prefix = pickRandom(FORCE_PREFIXES);
  const suffix = pickRandom(FORCE_SUFFIXES);
  return prefix + suffix;
}

/**
 * 批量生成名字
 */
export function generateNames(genre, count = 5) {
  const names = new Set();
  while (names.size < count) {
    names.add(generateName(genre));
  }
  return [...names];
}
