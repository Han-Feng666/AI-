/**
 * 根据角色性格生成符合其特质的台词
 */
export function generatePersonalityDialog(personality, genre) {
  const normGenre = normalizeGenre(genre);
  // 先匹配性格
  for (const [key, lines] of Object.entries(PERSONALITY_DIALOGS)) {
    if (personality && personality.includes(key)) {
      return pickRandom(lines);
    }
  }
  // 没匹配到性格，用题材台词
  const genreLines = GENRE_DIALOGS[normGenre] || GENRE_DIALOGS['通用'];
  return pickRandom(genreLines);
}

function pickRandom(arr) {
  return arr[Math.floor(Math.random() * arr.length)];
}

