export function extractJson(text) {
  if (!text) return null;
  let t = text.trim();
  // 去除 markdown 代码围栏
  const fence = t.match(/```(?:json)?\s*([\s\S]*?)```/);
  if (fence) t = fence[1].trim();
  // 去除注释（/* */ 和 //）
  t = t.replace(/\/\*[\s\S]*?\*\//g, '');
  // 规整常见非标准 JSON：控制字符、中文冒号、尾随逗号
  t = t
    .replace(/[\u0000-\u0008\u000b\u000c\u000e-\u001f]/g, ' ')
    .replace(/：/g, ':')
    .replace(/,\s*([}\]])/g, '$1');

  // 修复 JSON 字符串值内的未转义换行（弱模型常见，导致 JSON.parse 失败）
  // 策略：遍历字符串，在双引号内的裸换行 \n \r 替换为转义形式 \\n
  const fixNewlinesInStrings = (s) => {
    let out = '';
    let inStr = false;
    let escaped = false;
    for (let i = 0; i < s.length; i++) {
      const ch = s[i];
      if (inStr) {
        if (escaped) { out += ch; escaped = false; continue; }
        if (ch === '\\') { out += ch; escaped = true; continue; }
        if (ch === '"') { out += ch; inStr = false; continue; }
        if (ch === '\n') { out += '\\n'; continue; }
        if (ch === '\r') { out += '\\r'; continue; }
        if (ch === '\t') { out += '\\t'; continue; }
        out += ch;
      } else {
        if (ch === '"') { inStr = true; }
        out += ch;
      }
    }
    return out;
  };
  t = fixNewlinesInStrings(t);

  // 修复字符串值内误用英文双引号包裹的短语（弱模型常见，如 "外号"刀客"，性格孤傲"）
  // 启发式：成对英文引号之间是短中文短语，且两侧被中文包围，则视为引号对替换为中文引号
  const fixQuotePairs = (s) => s.replace(/([\u4e00-\u9fff。；、！？…（）])"([^"\\]{1,30}?)"(?=[\u4e00-\u9fff。；、！？…（）])/g, '$1“$2”');

  // 修复值内嵌套英文引号（弱模型常见，如 "外号"刀客"，性格孤傲" 破坏了 JSON 结构）
  // 策略：逐字符扫描，找出所有非结构引号；成对出现的非结构引号替换为中文引号
  const fixInnerQuotes = (s) => {
    const chars = s.split('');
    const n = chars.length;
    // 标记每个引号是否为结构引号
    const isStructural = new Array(n).fill(false);
    for (let i = 0; i < n; i++) {
      if (chars[i] !== '"') continue;
      // 前面非空白字符
      let prev = '';
      for (let j = i - 1; j >= 0; j--) {
        if (!/\s/.test(chars[j])) { prev = chars[j]; break; }
      }
      // 后面非空白字符
      let next = '';
      for (let j = i + 1; j < n; j++) {
        if (!/\s/.test(chars[j])) { next = chars[j]; break; }
      }
      // 结构引号特征：前面是 : { , [ 或开头（值/key 开始），或后面是 : , } ] （结束）
      const startMarker = (prev === ':' || prev === '{' || prev === ',' || prev === '[' || prev === '');
      const endMarker = (next === ':' || next === ',' || next === '}' || next === ']');
      if (startMarker || endMarker) {
        isStructural[i] = true;
      }
    }
    // 成对替换非结构引号：遇到第一个非结构引号记 pending，遇到第二个且中间无结构引号则成对替换
    const result = [];
    let pending = -1;
    let pendingPair = null;
    for (let i = 0; i < n; i++) {
      const ch = chars[i];
      if (ch === '"' && !isStructural[i]) {
        if (pending === -1) {
          pending = i;
          pendingPair = false;
          result.push('“');
        } else {
          // 检查两个非结构引号之间是否有结构引号（嵌套深度），简单处理：直接配对
          result.push('”');
          pending = -1;
        }
      } else {
        if (ch === '"' && isStructural[i]) {
          // 若当前处于 pending 非结构引号状态，说明结构被打断，重置
          pending = -1;
        }
        result.push(ch);
      }
    }
    return result.join('');
  };

  // 单引号键值转双引号（弱模型常见）
  const tryRelaxed = (s) => {
    try {
      // 先转中文逗号，再做单引号键值修复
      const norm = s.replace(/，/g, ',');
      return JSON.parse(norm.replace(/'([^']*)'(?=\s*[:,}\]])/g, '"$1"'));
    } catch { return null; }
  };
  const tryVariants = (s) => {
    // fixInnerQuotes/fixQuotePairs 必须在中文逗号转换之前执行（中文逗号作为值内引号的边界标记）
    const innerFixed = fixInnerQuotes(s);
    const quoteFixed = fixQuotePairs(s);
    const norm = (x) => x.replace(/，/g, ',');
    const candidates = [];
    candidates.push(norm(s));
    candidates.push(norm(quoteFixed));
    candidates.push(norm(innerFixed));
    candidates.push(norm(fixInnerQuotes(quoteFixed)));
    candidates.push(tryRelaxed(norm(s)));
    candidates.push(tryRelaxed(norm(innerFixed)));
    // 去除注释后的变体
    const noComment = (x) => x.replace(/\/\*[\s\S]*?\*\//g, '').replace(/\/\/.*/g, '');
    candidates.push(noComment(norm(s)));
    candidates.push(noComment(norm(innerFixed)));
    candidates.push(tryRelaxed(noComment(norm(s))));
    candidates.push(tryRelaxed(noComment(norm(innerFixed))));
    for (const c of candidates) {
      if (!c) continue;
      // tryRelaxed 返回的已是解析对象，直接返回
      if (typeof c === 'object' && c !== null) return c;
      try {
        const v = JSON.parse(c);
        return v;
      } catch { /* 继续 */ }
    }
    return null;
  };

  // 整体尝试（对象或数组）
  if ((t.startsWith('{') && t.endsWith('}')) || (t.startsWith('[') && t.endsWith(']'))) {
    const v = tryVariants(t);
    if (v) return v;
  }
  // 对象切片
  const objStart = t.indexOf('{');
  const objEnd = t.lastIndexOf('}');
  if (objStart !== -1 && objEnd > objStart) {
    const slice = t.slice(objStart, objEnd + 1);
    const v = tryVariants(slice);
    if (v) return v;
  }
  // 数组切片
  const arrStart = t.indexOf('[');
  const arrEnd = t.lastIndexOf(']');
  if (arrStart !== -1 && arrEnd > arrStart) {
    const slice = t.slice(arrStart, arrEnd + 1);
    const v = tryVariants(slice);
    if (v) return v;
  }
  // 多对象逐个提取：针对文本中有多个不连续 {…} 块（如前缀+对象+后缀）
  const objRegex = /\{[^{}]*\}/g;
  let objMatch;
  while ((objMatch = objRegex.exec(t)) !== null) {
    const v = tryVariants(objMatch[0]);
    if (v) return v;
  }
  // 多数组逐个提取
  const arrRegex = /\[[^\[\]]*\]/g;
  let arrMatch;
  while ((arrMatch = arrRegex.exec(t)) !== null) {
    const v = tryVariants(arrMatch[0]);
    if (v) return v;
  }
  return null;
}

