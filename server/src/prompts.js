  if (opts.knowledgeBlock && String(opts.knowledgeBlock).trim()) {
    sys += `\n\n${String(opts.knowledgeBlock).trim()}`;
  }
  // 注入技能库
  if (opts.skillsBlock && String(opts.skillsBlock).trim()) {
    sys += `\n\n${String(opts.skillsBlock).trim()}`;
  }
  // 注入题材指南（合并注入全部匹配的相关指南）
