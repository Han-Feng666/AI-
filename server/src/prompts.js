export function buildPlotFixSystem(styles, baseline, samples, presets) {
  let sys = PLOT_FIX_SYSTEM;
  if (presets && presets.length) {
    sys += `\n\n【创作风格要求】
本作选定的创作风格：${presets.join('、')}。

修复逻辑问题时保持这些风格基调，以自然细腻的叙述为底色。`;
  }
  if (baseline && String(baseline).trim()) {
    sys += `\n\n【本作文风基准（修复时必须遵循，保证全书风格统一）】\n${baseline}`;
  }
  if (samples && String(samples).trim()) {
    sys += `\n\n【真人文风参照（模仿其句子长短、语气、节奏与叙述口吻，而不是模仿人物与情节）】\n${String(samples).trim()}`;
  }
  if (styles && styles.length) {
    sys += `\n\n【本作采用的写作风格参考】
${styles.map((s) => `《${s.name}》：\n${s.analysis || ''}`).join('\n\n')}

修复逻辑问题时向这些风格自然靠拢。`;
  }
  return sys;
}

